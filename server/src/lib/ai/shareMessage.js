import { chat } from './model.js';

// 메모 → 양식장에 카카오톡·문자로 보낼 안내문 (1차 가공). 앱이 규칙으로 만든 초안을
// 받아 문장만 다듬는다: 새 사실을 만들지 않고, 메모에 없는 진단·처방을 넣지 않는다.
// 결과는 보내기 전에 직원이 직접 고친다 — 여기서는 저장하지 않는다.

const SYSTEM = `당신은 수산질병관리원 직원이 양식장 대표에게 보낼 카카오톡·문자 안내문을 다듬는 보조입니다.
규칙:
- 입력의 '현장 메모 원문'에 있는 사실만 씁니다. 수치·날짜·마릿수·약품명은 원문 그대로 둡니다.
- 원문에 없는 진단, 원인 추정, 처방, 약속을 새로 만들지 않습니다.
- 직원끼리만 쓰는 표현(@호출, 담당자 지정, '할일:' 같은 내부 표시, 내부 업무 지시)은 빼거나 양식장 입장의 안내로 바꿉니다.
- 정중하고 짧은 존댓말. 전체 700자 이내.
- 마크다운(#, **, 표) 금지. 목록은 '• '로 시작하는 줄로 씁니다. 카카오톡에서 그대로 보기 좋게 줄을 나눕니다.
- 초안의 머리말(관리원명·인사)과 맺음말(담당자 연락처)은 유지합니다.
- 다듬은 안내문 본문만 출력합니다. 설명이나 따옴표를 붙이지 않습니다.`;

export async function polishFarmMessage({ memo, farmName, draft, plan, onResult }) {
  const user = [
    `양식장: ${farmName ?? '미지정'}`,
    '',
    '현장 메모 원문:',
    memo.content,
    '',
    '규칙으로 만든 초안:',
    draft,
  ].join('\n');
  const { text, model } = await chat(SYSTEM, user, { plan, maxTokens: 1500, onResult });
  // 모델이 마크다운을 섞어 보내도 문자에서 깨지지 않게.
  const cleaned = text
    .replace(/^```[a-z]*\n?|```$/gm, '')
    .replace(/\*\*(.+?)\*\*/g, '$1')
    .replace(/^#+\s*/gm, '')
    .replace(/^[-*]\s+/gm, '• ')
    .trim();
  return { text: cleaned, model };
}
